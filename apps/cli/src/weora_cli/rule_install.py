"""按工具协议安装规则，保留用户文件和其他 Weora 功能写入的配置。"""

import hashlib
import json
import re
import sys
from pathlib import Path

from weora_cli import resource_delivery as delivery
from weora_cli.collab_client import CollabError, as_object, write_json
from weora_cli.commands import JsonValue
from weora_cli.resource_delivery import Object
from weora_cli.rule_adapters import RULE_TOOLS, home, inline_file, native_filename, render_native, rule_directory
from weora_cli.skill_adapters import dsh_hook_path, mount_dsh_bridge, zcode_hook_events


def agents(config: Object) -> list[str]:
    configured = delivery.values(config.get("agents", ["codex"]))
    if any(tool not in RULE_TOOLS for tool in configured):
        raise CollabError("RESOURCE_RUNTIME_UNKNOWN", "规则配置中包含未知的工具。")
    return configured


def hook_command(runtime: str) -> str:
    return delivery.HOOK if runtime == "codex" else f"{delivery.HOOK} --agent {runtime}"


def json_hook(path: Path, runtime: str, kind: str) -> None:
    delivery.safe_child(path.parent, path.name)
    config = delivery.read(path)
    hooks = as_object(config.setdefault("hooks", {}))
    command = hook_command(runtime)
    original = json.dumps(config)
    if kind == "process":
        hooks = zcode_hook_events(hooks)
        native_args: list[JsonValue] = ["-m", "weora_cli", "_resource-hook", "--agent", runtime]
        entry: Object = {"type": "process", "command": sys.executable, "args": native_args, "timeoutMs": 15000}
    else:
        entry = {"command": command}
        if kind != "cursor":
            entry.update({"type": "command", "timeout": 15})
    event = "sessionStart" if kind == "cursor" else "SessionStart"
    groups = hooks.setdefault(event, [])
    if not isinstance(groups, list):
        raise CollabError("RESOURCE_HOOK_INVALID", f"{path.name} 的启动钩子格式无效。")
    value: Object = entry if kind == "cursor" else {"hooks": [entry]}
    missing = value not in groups
    if missing:
        groups.append(value)
    if json.dumps(config) != original:
        write_json(path, config)


def install_dsh_hook(runtime: str, directory: Path) -> None:
    delivery.safe_child(directory, "cordis.patch.yml")
    json_hook(dsh_hook_path(directory), runtime, "cordis")
    mount_dsh_bridge(directory)


def install_pi_extension(directory: Path) -> None:
    target = delivery.safe_child(directory, "extensions/weora-rules.ts")
    # Pi 每轮重建 systemPrompt，从本机快照取规则并仅追加一次。
    script = """// Generated by Weora.
import { spawn } from "node:child_process";
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

export default function weoraRules(pi: ExtensionAPI) {
  pi.on("before_agent_start", async (event, ctx) => {
    const text = await new Promise<string>((resolve) => {
      const child = spawn(PYTHON, ["-m", "weora_cli", "_resource-hook", "--agent", "pi"],
        { stdio: ["pipe", "pipe", "ignore"], windowsHide: true });
      const timer = setTimeout(() => { child.kill(); resolve(""); }, 10000);
      let output = "";
      child.stdout.setEncoding("utf8");
      child.stdout.on("data", (value: string) => { output += value; });
      child.on("error", () => { clearTimeout(timer); resolve(""); });
      child.stdin.on("error", () => {});
      child.on("close", () => {
        clearTimeout(timer);
        try { resolve(JSON.parse(output).hookSpecificOutput?.additionalContext ?? ""); }
        catch { resolve(""); }
      });
      child.stdin.end(JSON.stringify({ hook_event_name: "SessionStart", cwd: ctx.cwd }));
    });
    return text ? { systemPrompt: event.systemPrompt + "\\n\\n" + text } : undefined;
  });
}
""".replace("PYTHON", json.dumps(sys.executable))
    if not target.exists() or target.read_text(encoding="utf-8") != script:
        delivery.write_text(target, script)


def install_hooks(tools: list[str], *, user: bool) -> None:
    for runtime in tools:
        directory = home(runtime)
        hook = RULE_TOOLS[runtime].hook
        if user:
            if runtime == "cursor":
                json_hook(directory / "hooks.json", runtime, "cursor")
        elif hook == "codex":
            delivery.install_hook(directory / "hooks.json", hook_command(runtime))
        elif hook == "process":
            json_hook(directory / "cli" / "config.json", runtime, hook)
        elif hook == "muse":
            json_hook(directory / "settings.json", runtime, hook)
        elif hook == "cordis":
            install_dsh_hook(runtime, directory)
        elif hook == "extension":
            install_pi_extension(directory)


def native_ledger(config_path: Path, root: Path) -> Path:
    return delivery.worktree_ledger(config_path, root).with_suffix(".native.json")


def retained_rules(config_path: Path, root: Path) -> set[str]:
    tracked = as_object(delivery.read(native_ledger(config_path, root)).get("files", {}))
    retained = set()
    for filename, record in tracked.items():
        path = Path(filename)
        value = as_object(record)
        if (
            path.is_file()
            and not path.is_symlink()
            and hashlib.sha256(path.read_bytes()).hexdigest() != value.get("hash")
        ):
            retained.add(str(value["name"]))
    return retained


def write_native_files(
    root: Path, tools: list[str], desired: dict[Path, tuple[str, str]], previous: Object, *, user: bool
) -> Object:
    directories = {
        directory
        for tool in set(tools) | set(agents({"agents": previous.get("agents", [])}))
        if (directory := rule_directory(tool, None if user else root)) is not None
    }
    known = as_object(previous.get("files", {}))
    tracked: Object = {}
    for path in set(desired) | {Path(name) for name in known}:
        location = next((d for d in directories if path.is_relative_to(d)), None)
        if location is None:
            raise CollabError("RESOURCE_STATE_INVALID", f"规则投递记录中的路径无效：{path.name}。")
        delivery.safe_child(location, path.relative_to(location).as_posix())
        old = as_object(known.get(str(path), {}))
        observed = hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else None
        if old and observed is not None and observed != old.get("hash"):
            # 个人修改保留在原处，后续 push 仍能追溯其团队规则名。
            tracked[str(path)] = old
            continue
        if path not in desired:
            if old and observed is not None:
                path.unlink()
            continue
        name, text = desired[path]
        current_hash = hashlib.sha256(text.encode("utf-8")).hexdigest()
        if observed is None or old:
            if observed != current_hash:
                delivery.write_text(path, text)
            tracked[str(path)] = {"name": name, "hash": current_hash}
    return tracked


_JSON_STRING = r'"(?:[^"\\]|\\.)*"'
_JSON_COMMENTS = re.compile(rf"{_JSON_STRING}|//[^\r\n]*|/\*[\s\S]*?\*/")
_JSON_TRAILING = re.compile(_JSON_STRING + r"|,(?=\s*[}\]])")


def open_code_document(path: Path) -> tuple[str, str, Object]:
    # JSONC 中掩码注释和末尾逗号，但保留索引，供调用方只替换 instructions 的值。
    text = path.read_text(encoding="utf-8-sig") if path.is_file() else "{}"
    sanitized = _JSON_COMMENTS.sub(
        lambda match: re.sub(r"[^\r\n]", " ", match[0]) if match[0].startswith("/") else match[0], text
    )
    sanitized = _JSON_TRAILING.sub(lambda match: " " if match[0] == "," else match[0], sanitized)
    try:
        return text, sanitized, as_object(json.loads(sanitized))
    except (ValueError, CollabError) as exc:
        raise CollabError("RESOURCE_CONFIG_INVALID", f"无法读取 OpenCode 配置 {path.name}。") from exc


def replace_instructions(text: str, sanitized: str, entries: list[str]) -> str:
    encoded = json.dumps(entries, ensure_ascii=False)
    opening = sanitized.index("{") + 1
    decoder = json.JSONDecoder()
    cursor = opening
    while sanitized[cursor:].lstrip()[:1] != "}":
        start = len(sanitized) - len(sanitized[cursor:].lstrip())
        key, end = decoder.raw_decode(sanitized, start)
        tail = sanitized[end:].lstrip()[1:].lstrip()
        value_start = len(sanitized) - len(tail)
        _, cursor = decoder.raw_decode(sanitized, value_start)
        if key == "instructions":
            return text[:value_start] + encoded + text[cursor:]
        if sanitized[cursor:].lstrip().startswith(","):
            cursor = sanitized.index(",", cursor) + 1
    delimiter = "," if sanitized[opening:].lstrip()[:1] != "}" else ""
    return text[:opening] + f'\n  "instructions": {encoded}{delimiter}\n' + text[opening:]


def opencode_instructions(root: Path, paths: set[Path], previous: Object, *, user: bool) -> Object:
    target = (home("opencode") if user else root / ".opencode") / "opencode.json"
    alternative = target.with_suffix(".jsonc")
    if alternative.is_file() and not target.is_file():
        target = alternative
    owned = set(delivery.values(previous.get("instructions", [])))
    if not paths and not owned:
        return {}
    delivery.safe_child(target.parent, target.name)
    desired = (
        sorted({path.parent.as_posix() + "/*.md" for path in paths})
        if user
        else ([".opencode/rules/**/*.md"] if paths else [])
    )
    text, sanitized, config = open_code_document(target)
    current = delivery.values(config.get("instructions", []))
    entries = [entry for entry in current if entry not in owned]
    managed = [entry for entry in desired if entry not in entries]
    if current != [*entries, *managed]:
        delivery.write_text(target, replace_instructions(text, sanitized, [*entries, *managed]))
    return {"instructions": [*managed]}


def apply_native(config_path: Path, root: Path, config: Object, selected: list[Object], *, user: bool) -> None:
    ledger = native_ledger(config_path, root)
    previous = delivery.read(ledger)
    tools = agents(config)
    directory = delivery.asset_root(config_path, root, user=user)
    snapshot = as_object(config.get("snapshot", {}))
    source = as_object(snapshot.get("files", {}))
    desired: dict[Path, tuple[str, str]] = {}
    opencode: set[Path] = set()
    for runtime in tools:
        target = rule_directory(runtime, None if user else root)
        if target is None:
            continue
        format_id = RULE_TOOLS[runtime].format
        if format_id in {"kiro", "omp"}:
            # 碰到展开后的同名路径时，根规则保留扁平名，命名空间规则保留原层级。
            names = [str(rule["name"]) for rule in selected]
            stems = [native_filename(format_id, name) for name in names]
            conflicts = {name for name in stems if stems.count(name) > 1}
        else:
            conflicts = set()
        for rule in selected:
            name = str(rule["name"])
            native = native_filename(format_id, name)
            if "/" in name and native in conflicts:
                native = name + ".md"
            output = delivery.safe_child(target, native)
            raw = source.get(str(rule["path"]))
            wanted = (
                name,
                render_native(format_id, rule, raw if isinstance(raw, str) else str(rule["body"]), directory),
            )
            if output in desired and desired[output] != wanted:
                raise CollabError("RESOURCE_FILE_CONFLICT", f"规则投递位置重复：{native}。")
            desired[output] = wanted
            if runtime == "opencode":
                opencode.add(output)

    files = write_native_files(root, tools, desired, previous, user=user)
    # 规则落盘后才能写激活引用。被保留的个人修改仍沿用原有引用。
    open_dir = rule_directory("opencode", None if user else root)
    if open_dir is not None:
        opencode.update(Path(filename) for filename in files if Path(filename).is_relative_to(open_dir))
    project_config = root / ".opencode" / "opencode.json"
    had_opencode = project_config.exists() or project_config.with_suffix(".jsonc").exists()
    instructions = opencode_instructions(root, opencode, previous, user=user)
    if not user:
        patterns = {
            "/" + re.sub(r"([!#\[\] ])", r"\\\1", Path(filename).relative_to(root).as_posix()) for filename in files
        }
        if not had_opencode and project_config.is_file():
            patterns.add("/.opencode/opencode.json")
        delivery.exclude_generated(root, patterns)
    targets = {str(target) for runtime in tools if user and (target := inline_file(runtime)) is not None}
    if user:
        text = delivery.render(selected, directory)
        for path in targets | set(delivery.values(previous.get("inline", []))):
            delivery.write_user_block(text if path in targets else "", Path(path))
    write_json(
        ledger,
        {
            "agents": [*dict.fromkeys(tools + agents({"agents": previous.get("agents", [])}))],
            "files": files,
            "inline": [*sorted(targets)],
            **instructions,
        },
    )
