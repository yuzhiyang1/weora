"""用成员在代码托管平台上的身份读取 PR/MR 事实。"""

import json
import netrc
import os
import re
import shutil
import subprocess
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Literal
from urllib.error import HTTPError, URLError
from urllib.parse import unquote, urlencode, urlsplit
from urllib.request import Request, build_opener

from weora_cli.collab_client import CollabError, _NoRedirect
from weora_cli.commands import JsonValue

Provider = Literal["github", "gitcode"]
_PART = re.compile(r"[a-zA-Z0-9_.-]+")
_DIFF_LIMIT = 3000
_RESPONSE_LIMIT = 4 * 1024**2
_GENERATED_COMMENTS = ("<!-- teamai:", "_Auto-generated by `teamai ci extract-mr`_", "<!-- weora:knowledge:")


@dataclass(frozen=True)
class ReviewRepository:
    provider: Provider
    api: str
    repository: str


@dataclass(frozen=True)
class ReviewTarget(ReviewRepository):
    number: str
    url: str


def _invalid_target() -> CollabError:
    return CollabError("KNOWLEDGE_MR_INVALID_TARGET", "请输入 GitHub PR 链接。")


def parse_target(source: str) -> ReviewTarget:
    """PR 链接只定位资源，请求始终发往固定的 GitHub API。"""
    try:
        url = urlsplit(source.strip())
        if url.scheme != "https" or url.netloc.lower() != "github.com":
            raise _invalid_target()
        repository, _, number = unquote(url.path).rstrip("/").lstrip("/").rpartition("/pull/")
        parts = repository.split("/")
        if (
            not re.fullmatch(r"[1-9][0-9]{0,17}", number)
            or len(parts) != 2
            or any(not _PART.fullmatch(part) or part in {".", ".."} for part in parts)
        ):
            raise _invalid_target()
    except (UnicodeError, ValueError) as exc:
        raise _invalid_target() from exc
    canonical = f"https://github.com/{repository}/pull/{number}"
    if len(canonical) > 1000:
        raise _invalid_target()
    return ReviewTarget("github", "https://api.github.com", repository, number, canonical)


def _environment_token(*names: str) -> str:
    for name in names:
        token = os.environ.get(name, "").strip()
        if token:
            if any(character.isspace() for character in token):
                raise CollabError("KNOWLEDGE_MR_TOKEN_INVALID", f"{name} 的格式无效。")
            return token
    return ""


def _netrc_token(host: str) -> str:
    try:
        auth = netrc.netrc(str(Path.home() / ".netrc")).hosts.get(host)
    except (OSError, netrc.NetrcParseError):
        return ""
    return auth[2] if auth and auth[2] and not any(c.isspace() for c in auth[2]) else ""


def _authorization(provider: Provider) -> dict[str, str]:
    if provider == "github":
        token = _environment_token("GITHUB_TOKEN", "GH_TOKEN")
        if not token and (gh := shutil.which("gh")):
            try:
                result = subprocess.run(
                    [gh, "auth", "token", "--hostname", "github.com"],
                    stdin=subprocess.DEVNULL,
                    capture_output=True,
                    text=True,
                    encoding="utf-8",
                    timeout=10,
                    check=False,
                    env=_github_environment(),
                )
                if not result.returncode:
                    token = result.stdout.strip()
            except (OSError, ValueError, subprocess.TimeoutExpired):
                pass
        # 公开 GitHub 仓库可匿名读取。
        return {"Authorization": f"Bearer {token}"} if token and not any(c.isspace() for c in token) else {}
    if provider == "gitcode" and (
        token := _environment_token("GITCODE_TOKEN", "GC_TOKEN") or _netrc_token("gitcode.com")
    ):
        return {"Authorization": "Bearer " + token}
    raise CollabError("KNOWLEDGE_MR_CREDENTIAL_REQUIRED", "请先配置对应代码托管平台的本机读取凭据。")


def _request(
    target: ReviewRepository,
    headers: dict[str, str],
    path: str,
    *,
    params: dict[str, str] | None = None,
    diff: bool = False,
    timeout: float = 30,
    method: str = "GET",
    payload: dict[str, JsonValue] | None = None,
) -> tuple[JsonValue, dict[str, str]]:
    url = target.api + path + ("?" + urlencode(params) if params else "")

    def read(authorization: dict[str, str]) -> tuple[JsonValue, dict[str, str]]:
        accept = "application/vnd.github.v3.diff" if diff else "application/json"
        request_headers = authorization | {"Accept": accept, "User-Agent": "weora-cli"}
        data = None
        if payload is not None:
            request_headers["Content-Type"] = "application/json"
            data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        request = Request(url, headers=request_headers, method=method, data=data)
        with build_opener(_NoRedirect()).open(request, timeout=timeout) as response:
            if diff:
                return response.read(_DIFF_LIMIT * 4).decode("utf-8", errors="replace")[:_DIFF_LIMIT], {}
            body = response.read(_RESPONSE_LIMIT + 1)
            if len(body) > _RESPONSE_LIMIT:
                raise CollabError("KNOWLEDGE_MR_RESPONSE_TOO_LARGE", "代码托管响应超过大小限制。")
            value: JsonValue = json.loads(body) if body else None
            info = {key.lower(): val for key, val in response.headers.items()}
            return value, info

    try:
        try:
            return read(headers)
        except HTTPError as first:
            first.close()
            if target.provider != "tgit" or first.code not in {401, 403}:
                raise
            alternative = (
                {"Authorization": "Bearer " + headers["PRIVATE-TOKEN"]}
                if "PRIVATE-TOKEN" in headers
                else {"PRIVATE-TOKEN": headers["Authorization"][7:]}
            )
            value = read(alternative)
            headers.clear()
            headers.update(alternative)
            return value
    except HTTPError as exc:
        exc.close()
        code = "KNOWLEDGE_MR_ACCESS_DENIED" if exc.code in {401, 403, 404} else "KNOWLEDGE_MR_HTTP_FAILED"
        raise CollabError(code, f"代码托管请求失败（HTTP {exc.code}）。", {"status": exc.code}) from exc
    except (URLError, OSError, ValueError, TimeoutError) as exc:
        raise CollabError("KNOWLEDGE_MR_UNAVAILABLE", "暂时无法读取代码托管数据。") from exc


def _object(value: JsonValue) -> dict[str, JsonValue]:
    if not isinstance(value, dict):
        raise CollabError("KNOWLEDGE_MR_INVALID_RESPONSE", "代码托管服务返回了无法读取的响应。")
    return value


def _rows(value: JsonValue) -> list[dict[str, JsonValue]]:
    if not isinstance(value, list):
        raise CollabError("KNOWLEDGE_MR_INVALID_RESPONSE", "代码托管服务返回了无法读取的列表。")
    return [_object(row) for row in value]


def hint_repository(remote: str) -> ReviewRepository | None:
    """会话启动查 GitHub origin，仓库地址仅作定位。"""
    scp = re.fullmatch(r"git@(github\.com):(.+)", remote.strip(), flags=re.IGNORECASE)
    try:
        url = urlsplit(f"ssh://{scp[1]}/{scp[2]}" if scp else remote.strip())
        if (
            url.scheme not in {"http", "https", "ssh"} or url.port is not None
            or url.query or url.fragment or url.hostname != "github.com"
        ):
            return None
        repository = unquote(url.path).strip("/").removesuffix(".git")
        parts = repository.split("/")
        if len(repository) > 850 or len(parts) < 2 or any(
            not _PART.fullmatch(part) or part in {".", ".."} for part in parts
        ):
            return None
        return ReviewRepository("github", "https://api.github.com", repository.lower()) if len(parts) == 2 else None
    except (ValueError, UnicodeError):
        return None


def merged_date(value: JsonValue) -> datetime | None:
    if isinstance(value, str):
        try:
            parsed = datetime.fromisoformat(value)
            return parsed.astimezone(UTC) if parsed.tzinfo is not None else None
        except (ValueError, OverflowError):
            pass
    return None


def _github_environment() -> dict[str, str]:
    return {key: value for key, value in os.environ.items() if key.upper() != "WEORA_COLLAB_TOKEN"}


def _github_merged(repo: ReviewRepository, limit: int) -> list[dict[str, JsonValue]] | None:
    if not (gh := shutil.which("gh")):
        return None
    try:
        result = subprocess.run(
            [
                gh, "pr", "list", "--repo", f"github.com/{repo.repository}", "--state", "merged",
                "--limit", str(limit), "--json", "number,title,mergedAt",
            ],
            stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, encoding="utf-8",
            timeout=8, check=False,
            env=_github_environment(),
        )
        return _rows(json.loads(result.stdout)) if not result.returncode else None
    except (OSError, ValueError, CollabError, subprocess.TimeoutExpired):
        return None


def recent_merges(repo: ReviewRepository, days: int, limit: int) -> list[JsonValue]:
    """只读近期合入记录。使用仓库身份构造出处，避免把托管服务提供的命令或链接带进 Hook。"""
    rows = _github_merged(repo, limit)
    if rows is None:
        path = f"/repos/{repo.repository}/pulls"
        query = {"state": "closed", "sort": "updated", "direction": "desc", "per_page": str(limit)}
        value, _ = _request(repo, _authorization(repo.provider), path, params=query, timeout=8)
        rows = _rows(value)
    cutoff = datetime.now(UTC) - timedelta(days=days)
    result: dict[str, JsonValue] = {}
    for row in rows[:limit]:
        when = merged_date(row.get("mergedAt", row.get("merged_at")))
        number = str(row.get("number"))
        title = _text(row.get("title"), 160)
        if when is None or when < cutoff or not re.fullmatch(r"[1-9][0-9]{0,17}", number) or not title:
            continue
        url = f"https://github.com/{repo.repository}/pull/{number}"
        result[url] = {"url": url, "title": title, "merged_at": when.isoformat()}
    return list(result.values())


def _pages(
    target: ReviewTarget,
    headers: dict[str, str],
    path: str,
    *,
    max_pages: int = 10,
    page_size: int = 100,
    strict: bool = False,
) -> list[dict[str, JsonValue]]:
    items = []
    for page in range(1, max_pages + 1):
        value, info = _request(target, headers, path, params={"page": str(page), "per_page": str(page_size)})
        if strict and (not isinstance(value, list) or any(not isinstance(row, dict) for row in value)):
            raise CollabError("KNOWLEDGE_MR_INVALID_RESPONSE", "评审评论或表态的分页响应无效。")
        rows = _rows(value)
        items.extend(rows)
        if "link" in info:
            more = bool(re.search(r'rel=["\']?next\b', info["link"]))
        elif "x-next-page" in info:
            next_page = info["x-next-page"].strip()
            if next_page and next_page != str(page + 1):
                raise CollabError("KNOWLEDGE_MR_INVALID_RESPONSE", "代码托管服务返回了无效的下一页。")
            more = bool(next_page) or len(rows) >= page_size
        else:
            more = len(rows) >= page_size
        if not more:
            return items
    raise CollabError("KNOWLEDGE_MR_PAGINATION_LIMIT", "评审或提交列表超过可读取页数。")


def _text(value: JsonValue, limit: int) -> str:
    return value.strip()[:limit] if isinstance(value, str) else ""


def _author(row: dict[str, JsonValue]) -> str:
    identity = row.get("user", row.get("author"))
    return _text(identity.get("login", identity.get("username")), 100) if isinstance(identity, dict) else ""


def _note(row: dict[str, JsonValue], author: str) -> dict[str, JsonValue] | None:
    body = row.get("body")
    if (
        not isinstance(body, str)
        or not body.strip()
        or row.get("system") is True
        or any(marker in body for marker in _GENERATED_COMMENTS)
    ):
        return None
    name = _author(row)
    return {"author": name, "role": "author" if name and name == author else "reviewer", "body": body.strip()[:500]}


def _discussion(
    target: ReviewTarget,
    auth: dict[str, str],
    repository: str,
    detail: str,
    author: str,
) -> list[JsonValue]:
    groups: dict[str, dict[str, JsonValue]] = {}
    paths = [
        ("inline", detail + "/comments"),
        ("review", detail + "/reviews"),
        ("comment", f"{repository}/issues/{target.number}/comments"),
    ]
    for kind, path in paths:
        for index, row in enumerate(_pages(target, auth, path)):
            if kind == "review" and row.get("state") == "PENDING":
                continue
            if not (note := _note(row, author)):
                continue
            reference = (
                row.get("in_reply_to_id") or row.get("id")
                if kind == "inline"
                else row.get("discussion_id", row.get("id"))
            )
            group = groups.setdefault(
                f"{kind}:{reference if reference is not None else index}",
                {
                    "path": row.get("path"),
                    "line": row.get("line", row.get("original_line")),
                    "state": row.get("state"),
                    "notes": [],
                },
            )
            notes = group["notes"]
            assert isinstance(notes, list)
            notes.append(note)

    # 已达成的评审决定和有回复的讨论优先，预算按整条讨论裁剪。
    def priority(item: dict[str, JsonValue]) -> tuple[bool, int]:
        notes = item["notes"]
        assert isinstance(notes, list)
        return item.get("resolved") is True, len(notes)

    groups_ordered = sorted(groups.values(), key=priority, reverse=True)
    result: list[JsonValue] = []
    remaining = 6000
    for group in groups_ordered:
        notes = group["notes"]
        assert isinstance(notes, list)
        if len(notes) > 2 and len(json.dumps(notes, ensure_ascii=False)) > 1500:
            group["notes"] = [notes[0], notes[-1]]
        size = len(json.dumps(group, ensure_ascii=False))
        if size <= remaining:
            result.append(group)
            remaining -= size
    return result


def _review_detail(
    target: ReviewTarget, auth: dict[str, str],
) -> tuple[str, str, str, dict[str, JsonValue]]:
    """从已验证的来源取得 API 路径和同一个评审记录。"""

    repo = "/repos/" + target.repository
    detail = f"{repo}/pulls/{target.number}"
    row = _object(_request(target, auth, detail)[0])
    if str(row.get("number")) != target.number:
        raise CollabError("KNOWLEDGE_MR_MISMATCH", "代码托管服务返回了其他评审记录。")
    return repo, detail, detail + "/files", row


def _commit(*values: JsonValue) -> str | None:
    return next((
        value.lower() for value in values
        if isinstance(value, str) and re.fullmatch(r"[0-9a-fA-F]{40}|[0-9a-fA-F]{64}", value)
    ), None)


def _source_commit(row: dict[str, JsonValue]) -> str | None:
    head = row.get("head")
    diffs = row.get("diff_refs")
    return _commit(
        head.get("sha") if isinstance(head, dict) else None,
        row.get("sha"), diffs.get("head_sha") if isinstance(diffs, dict) else None, row.get("last_commit_sha"),
    )


@dataclass(frozen=True)
class CiReviewState:
    """固定评审源版本。没有可靠的合并时间及提交时，不允许执行发布。"""

    head_commit: str
    merge_commit: str | None
    merged_at: datetime | None
    reviewable: bool | None = None


def ci_reviewable(row: dict[str, JsonValue]) -> bool | None:
    """识别可接收自动建议的评审，缺少有效状态时由调用方重试。"""
    state = row.get("state")
    if row.get("merged") is True or state in ("closed", "merged", "locked"):
        return False
    if state in ("open", "opened"):
        return row.get("draft") is not True and row.get("work_in_progress") is not True
    return None


def require_ci_reviewable(reviewable: bool | None) -> None:
    if reviewable is None:
        raise CollabError("KNOWLEDGE_CI_REVIEW_STATE_UNKNOWN", "代码托管平台未返回有效的评审状态。")
    if not reviewable:
        raise CollabError("KNOWLEDGE_CI_REVIEW_INACTIVE", "评审已关闭或仍为草稿，忽略自动建议。")


def read_ci_state(target: ReviewTarget) -> CiReviewState:
    _, _, _, row = _review_detail(target, _authorization(target.provider))
    head = _source_commit(row)
    if head is None:
        raise CollabError("KNOWLEDGE_CI_HEAD_MISSING", "代码托管平台未返回完整的源提交。")
    merged = row.get("merged") is True
    when = merged_date(row.get("merged_at")) if merged else None
    commit = _commit(row.get("merge_commit_sha"))
    if merged and (when is None or commit is None):
        raise CollabError("KNOWLEDGE_CI_MERGE_MISSING", "代码托管平台未返回完整的合并提交及时间。")
    return CiReviewState(head, commit if merged else None, when, ci_reviewable(row))


def _check_preview_head(review: dict[str, JsonValue], head: str) -> None:
    if _source_commit(review) != head:
        raise CollabError("KNOWLEDGE_CI_HEAD_CHANGED", "评审源提交已变化，请重新运行图谱预览。")


def ci_diff_base(target: ReviewTarget, head: str) -> str:
    """取得评审差异的共同祖先。目标分支尖端可能包含与本评审无关的提交。"""
    auth = _authorization(target.provider)
    repo, _, _, review = _review_detail(target, auth)
    _check_preview_head(review, head)
    branch = review.get("base")
    tip = _commit(branch.get("sha")) if isinstance(branch, dict) else None
    if tip is not None:
        comparison = _object(_request(
            target, auth, f"{repo}/compare/{tip}...{head}", params={"per_page": "1"},
        )[0])
        ancestor = comparison.get("merge_base_commit")
        base = _commit(ancestor.get("sha")) if isinstance(ancestor, dict) else None
        if base is not None:
            return base
    raise CollabError("KNOWLEDGE_CI_BASE_MISSING", "代码托管平台未返回绑定到源提交的差异基线。")


def ci_changed_paths(target: ReviewTarget, *, expected_head: str | None = None) -> tuple[str, ...]:
    """返回合并包含的文件，重命名和删除也要使原有代码证据失效。"""
    auth = _authorization(target.provider)
    _, _, files_path, review = _review_detail(target, auth)
    if expected_head is not None:
        _check_preview_head(review, expected_head)
    files = _pages(target, auth, files_path, max_pages=32)
    if expected_head is not None:
        _check_preview_head(_review_detail(target, auth)[3], expected_head)
    return tuple(dict.fromkeys(
        value for row in files for key in ("filename", "previous_filename", "old_path", "new_path")
        if isinstance(value := row.get(key), str) and value
    ))


def read_review(target: ReviewTarget, *, discussions: bool) -> dict[str, JsonValue]:
    auth = _authorization(target.provider)
    repo, detail, _, row = _review_detail(target, auth)
    title, author = _text(row.get("title"), 160), _author(row)
    if not title:
        raise CollabError("KNOWLEDGE_MR_INVALID_RESPONSE", "代码托管服务未返回评审标题。")
    warnings: list[JsonValue] = []
    commits: list[str] = []
    for entry in _pages(target, auth, detail + "/commits", max_pages=3):
        nested = entry.get("commit")
        message = nested.get("message") if isinstance(nested, dict) else entry.get("title") or entry.get("message")
        revision = _text(entry.get("sha", entry.get("id")), 12)
        summary = _text(message, 300).partition("\n")[0]
        commits.append(f"{revision} {summary}")
    diff = _text(_request(target, auth, detail, diff=True)[0], _DIFF_LIMIT)
    threads: list[JsonValue] = []
    if discussions:
        try:
            threads = _discussion(target, auth, repo, detail, author)
        except CollabError as exc:
            warnings.append({"stage": "discussions", "code": exc.code})
    return {
        "title": title,
        "author": author,
        "state": _text(row.get("state"), 80),
        "head_commit": _source_commit(row),
        "date": _text(row.get("merged_at"), 80),
        "description": _text(row.get("body", row.get("description")), 12000),
        "commits": "\n".join(commits)[:12000],
        "diff": diff,
        "discussions": threads,
        "warnings": warnings,
    }
